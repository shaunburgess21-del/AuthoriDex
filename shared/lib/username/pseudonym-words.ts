/**
 * Word pools for onboarding pseudonym generation (Adj + Noun + 1–99).
 * Words are PascalCase, 3–10 chars so combined handles stay within 30.
 */
function dedupeWords(words: readonly string[]): readonly string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const w of words) {
    if (w.length < 3 || w.length > 10) continue;
    if (seen.has(w)) continue;
    seen.add(w);
    out.push(w);
  }
  return out;
}

